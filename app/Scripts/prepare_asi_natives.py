#!/usr/bin/env python3
"""Game commands (natives) for Script Hook V mods (.asi), GTA-69.

A mod calls a native by its Script Hook V hash (nativeInit/nativePush64/nativeCall). The engine's
native handlers are named after the native (`<x>_commands::SetupScriptCommands()::scrWrapped_NAME::Call(
rage::scrThread::Info&)`, builtins `rage::scrThread::Name(rage::scrThread::Info&)`), so each hash in
Scripts/asi_native_hashes.txt (name and older names) maps to its handler by name. A few natives share
another's handler under a second name (ALIASES). Some have no handler of their own: the engine
registers the command function itself (`player_commands::CommandPlayerId()`); those get a small
wrapper here that unpacks the arguments by the function's wasm signature. Writes
Generated/asi-natives.inc: a table sorted by hash for Source/EngineHost.c.
"""
import re
from pathlib import Path
from engine_names import TABLE

root = Path(__file__).resolve().parents[1]
# Natives the engine registers on another native's handler (same arguments and behaviour).
ALIASES = {
    'SET_PED_AS_NO_LONGER_NEEDED': 'SET_ENTITY_AS_NO_LONGER_NEEDED',
    'SET_VEHICLE_AS_NO_LONGER_NEEDED': 'SET_ENTITY_AS_NO_LONGER_NEEDED',
    'SET_OBJECT_AS_NO_LONGER_NEEDED': 'SET_ENTITY_AS_NO_LONGER_NEEDED',
}
handlers, builtins, commands = {}, {}, {}
for line in open(TABLE):
    index, _, label = line.rstrip('\n').partition('\t')
    m = re.search(r'scrWrapped_([A-Z0-9_]+)::Call\(rage::scrThread::Info&\)$', label)
    if m: handlers[m.group(1)] = int(index); continue
    m = re.match(r'[a-z_]+::Command([A-Za-z0-9]+)\(', label)
    if m: commands.setdefault(m.group(1).lower(), []).append(int(index))
    m = re.match(r'rage::scrThread::([A-Za-z0-9]+)\(rage::scrThread::Info&\)$', label)
    if m: builtins[m.group(1).lower()] = int(index)
def camel(name): return ''.join(part.capitalize() for part in name.lstrip('_').split('_')).lower()
# The wasm2c prototype of each command function, for the wrappers.
prototypes = {}
for path in sorted((root / 'Generated').glob('game_*.c')):
    for m in re.finditer(r'^(u32|u64|f32|f64|void) w2c_game_f(\d+)\(w2c_game\* instance((?:, (?:u32|u64|f32|f64) var_p\d+)*)\) \{', path.read_text(), re.M):
        prototypes[int(m.group(2))] = (m.group(1), re.findall(r'(u32|u64|f32|f64) var_p', m.group(3)))
wrappers = []
def wrap(function, name):
    result, params = prototypes[function]
    if 'f64' in params or result == 'f64': return None
    # Arguments are 8-byte slots (a float in the low 4 bytes); pointers stay engine addresses.
    args = ', '.join(f'(u32)slot[{i}]' if t == 'u32' else f'pg_asi_f32(slot[{i}])' if t == 'f32' else f'slot[{i}]' for i, t in enumerate(params))
    call = f'w2c_game_f{function}(game{", " + args if args else ""})'
    body = {'void': f'{call};', 'u32': f'u64 value = (u32){call}; memcpy(pg_pointer(&env, out, 8), &value, 8);',
            'u64': f'u64 value = {call}; memcpy(pg_pointer(&env, out, 8), &value, 8);',
            'f32': f'f32 value = {call}; u64 bits = 0; memcpy(&bits, &value, 4); memcpy(pg_pointer(&env, out, 8), &bits, 8);'}[result]
    wrappers.append(f'{result} w2c_game_f{function}(w2c_game*{"".join(", " + t for t in params)});\n'
                    f'static void pg_asi_{name.lower()}(w2c_game *game, u64 info) {{  // {name}\n'
                    f'  u64 out, from; memcpy(&out, pg_pointer(&env, info, 8), 8); memcpy(&from, pg_pointer(&env, info + 16, 8), 8);\n'
                    f'  const u64 *slot = pg_pointer(&env, from, 8 * {max(len(params), 1)}); (void)slot;\n  {body}\n}}')
    return f'pg_asi_{name.lower()}'
rows, missing = [], 0
for line in open(root / 'Scripts/asi_native_hashes.txt'):
    if line.startswith('#') or not line.strip(): continue
    hash_, *names = line.split()
    found = None
    for name in names:
        name = ALIASES.get(name, name)
        if name in handlers: found = handlers[name]; break
        if camel(name) in builtins: found = builtins[camel(name)]; break
        if len(commands.get(camel(name), [])) == 1 and commands[camel(name)][0] in prototypes:
            found = wrap(commands[camel(name)][0], names[0])
            if found: break
    if found is None: missing += 1; continue
    rows.append((int(hash_, 16), found, names[0]))
rows.sort()
functions = sorted({f for _, f, _ in rows if isinstance(f, int)})
out = ['// Generated by Scripts/prepare_asi_natives.py: Script Hook V native hash -> engine handler.',
       'static inline f32 pg_asi_f32(u64 slot) { f32 value; uint32_t bits = (uint32_t)slot; memcpy(&value, &bits, 4); return value; }']
out += [f'void w2c_game_f{f}(w2c_game*, u64);' for f in functions]
out += wrappers
out.append('static const struct { uint64_t hash; void (*handler)(w2c_game *, u64); } pg_asi_natives[] = {')
out += [f'  {{0x{h:016x}ull, {f if isinstance(f, str) else "w2c_game_f" + str(f)}}},  // {name}' for h, f, name in rows]
out.append('};')
target = root / 'Generated/asi-natives.inc'
text = '\n'.join(out) + '\n'
if not target.exists() or target.read_text() != text: target.write_text(text)
print(f'asi natives: {len(rows)} game commands for mods ({len(wrappers)} through wrappers), {missing} not in this game build')
